//! atlas-tool: bakes the style-2a art into the game's texture atlas.
//!
//! Inputs (all under the repo root):
//! - `art/icons/*.icon-only.svg`: part glyphs without their tile. Each SVG contains its own soft glow as a
//!   `<g filter="url(#gl)" opacity="0.55">` group. The tool renders the crisp glyph (glow group removed) and
//!   the glow (glow group alone, opacity baked in) into separate regions, so the game can draw or skip the
//!   glow (bloom vs. pre-blurred sprites).
//! - `art/tokens.json`: style tokens. Flattened into the index so the game never hard-codes colours.
//!
//! Outputs (committed):
//! - `crates/game/assets/atlas/atlas.png`: straight-alpha sRGB RGBA, transparent texels colour-dilated so
//!   bilinear filtering and mipmaps never pull in dark fringes.
//! - `crates/game/assets/atlas/atlas.txt`: the index (regions in pixels plus their size in ship cells and an
//!   anchor point), followed by the flattened style tokens.
//!
//! Run from anywhere: `cargo run -p atlas-tool --release` (optionally pass the repo root as the first argument).
//! Re-run whenever an SVG under `art/icons/` or `art/tokens.json` changes.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use resvg::{tiny_skia, usvg};

/// Atlas pixels per ship cell for icons and other crisp art.
const CELL_PX: u32 = 128;
/// Soft FX (plumes) don't need the full resolution.
const SOFT_CELL_PX: u32 = 64;
/// SVG user units per ship cell in all art sources.
const UNITS_PER_CELL: f32 = 20.0;
/// Transparent gutter between regions (keeps mip levels down to 1/8 clean).
const PAD: u32 = 8;
const ATLAS_WIDTH: u32 = 2048;
/// Atlas height is rounded up to a multiple of this so every mip level has integer size.
const HEIGHT_ALIGN: u32 = 64;

struct Region {
    name: String,
    w: u32,
    h: u32,
    /// Straight (non-premultiplied) RGBA8.
    rgba: Vec<u8>,
    /// Size of the region in ship cells.
    cells: (f32, f32),
    /// Anchor point in cells from the region's top-left corner (e.g. a nozzle or a barrel tip).
    origin: (f32, f32),
}

fn main() {
    let root = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../.."));
    let root = root.canonicalize().expect("repo root");
    let tokens_src = fs::read_to_string(root.join("art/tokens.json")).expect("read art/tokens.json");
    let tokens: serde_json::Value = serde_json::from_str(&tokens_src).expect("parse art/tokens.json");

    let mut regions = Vec::new();
    bake_icons(&root.join("art/icons"), &mut regions);
    bake_fx(&tokens, &mut regions);

    let (w, h, mut atlas, placed) = pack(&regions);
    dilate(&mut atlas, w, h, 16);

    let out_dir = root.join("crates/game/assets/atlas");
    fs::create_dir_all(&out_dir).expect("create output dir");
    write_png(&out_dir.join("atlas.png"), w, h, &atlas);

    let mut index = String::new();
    index.push_str("# Generated by `cargo run -p atlas-tool --release` from art/icons/*.icon-only.svg and art/tokens.json.\n");
    index.push_str("# Do not edit by hand; re-run the tool instead.\n");
    let _ = writeln!(index, "atlas {w} {h}");
    index.push_str("# region <name> <x> <y> <w> <h> <cells_w> <cells_h> <origin_x> <origin_y>  (pixels, then ship cells)\n");
    for (r, (x, y)) in regions.iter().zip(&placed) {
        let _ = writeln!(
            index,
            "region {} {} {} {} {} {} {} {} {}",
            r.name, x, y, r.w, r.h, r.cells.0, r.cells.1, r.origin.0, r.origin.1
        );
    }
    index.push_str("# token <dotted.path> <value>  (art/tokens.json, flattened)\n");
    flatten_tokens("", &tokens, &mut index);
    fs::write(out_dir.join("atlas.txt"), index).expect("write atlas.txt");

    let png_size = fs::metadata(out_dir.join("atlas.png")).map(|m| m.len()).unwrap_or(0);
    println!(
        "atlas {}x{} with {} regions -> {} ({} KiB)",
        w,
        h,
        regions.len(),
        out_dir.join("atlas.png").display(),
        png_size / 1024
    );
}

// ---------------------------------------------------------------------------------------------------------
// Icons

fn bake_icons(dir: &Path, out: &mut Vec<Region>) {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .expect("read art/icons")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.to_string_lossy().ends_with(".icon-only.svg"))
        .collect();
    files.sort();
    for path in files {
        let file = path.file_name().unwrap().to_string_lossy().to_string();
        let stem = file.trim_end_matches(".icon-only.svg").to_string();
        let src = fs::read_to_string(&path).expect("read icon svg");
        let (vb_w, vb_h) = view_box_size(&src).unwrap_or_else(|| panic!("{file}: no viewBox"));
        let cells = (vb_w / UNITS_PER_CELL, vb_h / UNITS_PER_CELL);
        let (pw, ph) = ((cells.0 * CELL_PX as f32).round() as u32, (cells.1 * CELL_PX as f32).round() as u32);

        let (crisp_svg, glow_svg) = split_glow(&src);
        out.push(Region {
            name: format!("icon/{stem}"),
            w: pw,
            h: ph,
            rgba: render_svg(&crisp_svg, pw, ph),
            cells,
            origin: (0.0, 0.0),
        });
        if let Some(glow_svg) = glow_svg {
            out.push(Region {
                name: format!("glow/{stem}"),
                w: pw,
                h: ph,
                rgba: render_svg(&glow_svg, pw, ph),
                cells,
                origin: (0.0, 0.0),
            });
        }
    }
}

fn view_box_size(svg: &str) -> Option<(f32, f32)> {
    let start = svg.find("viewBox=\"")? + "viewBox=\"".len();
    let end = start + svg[start..].find('"')?;
    let nums: Vec<f32> = svg[start..end].split_whitespace().filter_map(|n| n.parse().ok()).collect();
    (nums.len() == 4).then(|| (nums[2], nums[3]))
}

/// Splits an icon SVG into (crisp glyph, glow-only) documents. The glow is every `<g filter="url(#gl)" ...>`
/// element (with its opacity) found after `</defs>`.
fn split_glow(src: &str) -> (String, Option<String>) {
    let defs_end = src.find("</defs>").map(|i| i + "</defs>".len()).unwrap_or_else(|| src.find('>').unwrap() + 1);
    let svg_end = src.rfind("</svg>").expect("</svg>");
    let head = &src[..defs_end];
    let body = &src[defs_end..svg_end];

    let mut crisp = String::new();
    let mut glow = String::new();
    let mut rest = body;
    while let Some(start) = rest.find("<g filter=\"url(#gl)\"") {
        crisp.push_str(&rest[..start]);
        let len = balanced_g_len(&rest[start..]);
        glow.push_str(&rest[start..start + len]);
        rest = &rest[start + len..];
    }
    crisp.push_str(rest);
    let crisp_doc = format!("{head}{crisp}</svg>");
    let glow_doc = (!glow.is_empty()).then(|| format!("{head}{glow}</svg>"));
    (crisp_doc, glow_doc)
}

/// Length of the `<g ...> ... </g>` element starting at `s[0]`, honouring nested groups.
fn balanced_g_len(s: &str) -> usize {
    let bytes = s.as_bytes();
    let mut depth = 0i32;
    let mut i = 0;
    while i < bytes.len() {
        if s[i..].starts_with("</g>") {
            depth -= 1;
            i += 4;
            if depth == 0 {
                return i;
            }
            continue;
        }
        if s[i..].starts_with("<g") && matches!(bytes.get(i + 2), Some(b' ') | Some(b'>')) {
            // A self-closing group doesn't change depth.
            let close = s[i..].find('>').expect("unterminated tag") + i;
            if bytes[close - 1] != b'/' {
                depth += 1;
            }
            i = close + 1;
            continue;
        }
        i += 1;
    }
    panic!("unbalanced <g> in icon svg");
}

